#!/usr/bin/env python3
"""Generates the Metal (MSL) shaders from the checked-in SPIR-V ones, for the SDL GPU device on macOS.
  python3 tools/gen_msl.py            (needs spirv-cross: brew install spirv-cross)
Reads src/render/shaders/generated/*.spv.h and writes the matching *.msl.h next to them. Run it again after the SPIR-V changes."""
import glob, os, re, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "..", "src", "render", "shaders", "generated")


def spirv_bytes(text):
    return bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", text))


def main():
    for path in sorted(glob.glob(os.path.join(GEN, "*.spv.h"))):
        name = os.path.basename(path)[: -len(".spv.h")]  # e.g. main_vert
        stage = "vert" if name.endswith("_vert") else "frag"
        with tempfile.TemporaryDirectory() as d:
            spv, msl = os.path.join(d, name + ".spv"), os.path.join(d, name + ".metal")
            open(spv, "wb").write(spirv_bytes(open(path).read()))
            r = subprocess.run(["spirv-cross", "--msl", "--msl-version", "20000", "--stage", stage, spv, "--output", msl], capture_output=True, text=True)
            if r.returncode != 0:
                sys.exit(f"gen_msl: spirv-cross failed on {name}: {r.stderr.strip()}")
            src = open(msl, "rb").read()
        var = "k" + "".join(p.capitalize() for p in name.split("_")) + "Msl"  # main_vert -> kMainVertMsl
        rows = ["    " + ",".join(f"0x{b:02x}" for b in src[i:i + 24]) + "," for i in range(0, len(src), 24)]
        out = os.path.join(GEN, name + ".msl.h")
        with open(out, "w") as f:
            f.write(f"// Generated by tools/gen_msl.py from {name}.spv.h (spirv-cross, MSL). Do not edit.\n#pragma once\n")
            f.write(f"static const unsigned char {var}[{len(src)}] = {{\n" + "\n".join(rows) + "\n};\n")
        print(f"{name}: {len(src)} bytes -> {os.path.basename(out)}")


main()
